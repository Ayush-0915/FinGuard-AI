"""
FinGuard AI — Phase 3: Investigator Case Builder
Synthesizes individual alerts, graph typologies, connected accounts, and timelines
into structured, dashboard-ready investigatory case files.

Strictly preserves:
- Deterministic case identifiers
- Traceability across all associated transactions and counterparty nodes
- Clear operational review status tracking (Open, In Review, Escalated, Closed)
- Explicit non-guilt investigatory lead disclaimers
"""

from typing import List, Dict, Any, Optional
import pandas as pd
import numpy as np

DISCLAIMER_TEXT = (
    "NOTICE: This case file represents an automated investigatory lead generated by FinGuard AI "
    "based on statistical anomaly detection and graph topology signals. It is designed to assist "
    "compliance analysts and does not constitute a confirmed financial crime, legal determination, "
    "or proof of illicit activity."
)

class CaseBuilder:
    def __init__(self, default_status: str = "Open"):
        self.default_status = default_status

    def build_case_from_alerts(
        self,
        primary_account: str,
        alerts: List[Dict[str, Any]],
        graph_patterns: Optional[List[Dict[str, Any]]] = None,
        case_id: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Constructs a structured investigation case file centered on a primary account.
        """
        if not alerts:
            raise ValueError("Cannot construct a case with zero alerts.")

        # Sort alerts chronologically
        sorted_alerts = sorted(
            alerts,
            key=lambda a: (a.get("timestamp", ""), a.get("transaction_id", ""))
        )

        # Extract connected counterparties
        related_accounts = set()
        tx_ids = []
        total_volume = 0.0
        scores = []
        ranks = []
        tiers = []

        for a in sorted_alerts:
            s = a.get("sender_account", "")
            r = a.get("receiver_account", "")
            if s and s != primary_account:
                related_accounts.add(s)
            if r and r != primary_account:
                related_accounts.add(r)
            tx_ids.append(a.get("transaction_id", ""))
            total_volume += float(a.get("amount", 0.0))
            if "model_risk_score" in a:
                scores.append(float(a["model_risk_score"]))
            if "risk_rank" in a and a["risk_rank"]:
                ranks.append(int(a["risk_rank"]))
            if "risk_tier" in a:
                tiers.append(a["risk_tier"])

        # Determine overall case priority tier
        if "Critical" in tiers:
            case_tier = "Critical"
        elif "High" in tiers:
            case_tier = "High"
        elif "Medium" in tiers:
            case_tier = "Medium"
        else:
            case_tier = "Low"

        best_rank = min(ranks) if ranks else None
        max_score = max(scores) if scores else 0.0

        # Deterministic Case ID
        first_date = str(sorted_alerts[0].get("timestamp", "20220901"))[:10].replace("/", "").replace("-", "")
        cid = case_id or f"CASE-{primary_account[:8]}-{first_date}"

        # Construct chronological timeline
        timeline = []
        for i, a in enumerate(sorted_alerts, 1):
            timeline.append({
                "step": i,
                "timestamp": a.get("timestamp", "N/A"),
                "transaction_id": a.get("transaction_id", "N/A"),
                "sender": a.get("sender_account", "N/A"),
                "receiver": a.get("receiver_account", "N/A"),
                "amount": float(a.get("amount", 0.0)),
                "currency": a.get("currency", "N/A"),
                "score": float(a.get("model_risk_score", 0.0)),
                "summary": a.get("human_readable_summary", f"Transfer of ${float(a.get('amount', 0.0)):,.2f}")
            })

        # Synthesize Graph Patterns
        patterns_summary = []
        if graph_patterns:
            for p in graph_patterns:
                patterns_summary.append({
                    "typology": p.get("typology_name", p.get("typology")),
                    "severity": p.get("severity_score", 0.7),
                    "confidence": p.get("confidence_level", "MEDIUM"),
                    "explanation": p.get("investigator_explanation")
                })

        # Case Narrative Summary
        investigation_narrative = (
            f"Case {cid} opened for primary entity {primary_account}. "
            f"Encompasses {len(sorted_alerts)} suspicious transactions totalling ${total_volume:,.2f} "
            f"across {len(related_accounts)} connected counterparties. "
            f"Peak model risk score: {max_score*100:.1f}% ({case_tier} Priority). "
        )
        if patterns_summary:
            typologies_str = ", ".join(p["typology"] for p in patterns_summary)
            investigation_narrative += f"Identified {len(patterns_summary)} graph pattern(s): {typologies_str}."

        return {
            "case_id": cid,
            "review_status": self.default_status,
            "priority_tier": case_tier,
            "best_alert_rank": best_rank,
            "peak_risk_score": round(max_score, 4),
            "primary_account": primary_account,
            "total_suspicious_volume": round(total_volume, 2),
            "alert_count": len(sorted_alerts),
            "connected_accounts_count": len(related_accounts),
            "related_accounts": sorted(list(related_accounts)),
            "relevant_transaction_ids": tx_ids,
            "detected_graph_patterns": patterns_summary,
            "activity_timeline": timeline,
            "investigation_summary": investigation_narrative,
            "compliance_disclaimer": DISCLAIMER_TEXT
        }
